_LAUNCHER_TEMPLATE = '''"""Auto-generated by basicdet.models.reid_clipreid — do not edit."""
import glob
import os.path as osp
import re
import runpy
import sys

from datasets import make_dataloader_clipreid as _mdl
from datasets.bases import BaseImageDataset

_NAME_RE = re.compile(r"^(-?\\d+)_c(\\d+)")


class PersondetReID(BaseImageDataset):
    """Market-1501-layout dataset without Market's pid/camid range asserts."""

    def __init__(self, root="", verbose=True, **kwargs):
        super().__init__()
        self.dataset_dir = root
        train, cam_map = self._scan(osp.join(root, "bounding_box_train"), relabel=True)
        query, _ = self._scan(osp.join(root, "query"), relabel=False, cam_map=cam_map)
        gallery, _ = self._scan(
            osp.join(root, "bounding_box_test"), relabel=False, cam_map=cam_map
        )
        self.train, self.query, self.gallery = train, query, gallery
        (self.num_train_pids, self.num_train_imgs, self.num_train_cams,
         self.num_train_vids) = self.get_imagedata_info(train)
        (self.num_query_pids, self.num_query_imgs, self.num_query_cams,
         self.num_query_vids) = self.get_imagedata_info(query)
        (self.num_gallery_pids, self.num_gallery_imgs, self.num_gallery_cams,
         self.num_gallery_vids) = self.get_imagedata_info(gallery)
        if verbose:
            print("=> persondet ReID loaded")
            self.print_dataset_statistics(train, query, gallery)

    def _scan(self, split_dir, relabel, cam_map=None):
        paths = sorted(glob.glob(osp.join(split_dir, "*.jpg")))
        paths += sorted(glob.glob(osp.join(split_dir, "*.png")))
        raw = []
        for p in paths:
            m = _NAME_RE.match(osp.basename(p))
            if m is None:
                raise ValueError("not a Market-style name: " + p)
            raw.append((p, int(m.group(1)), int(m.group(2))))
        raw = [(p, pid, cam) for p, pid, cam in raw if not (relabel and pid == -1)]
        if cam_map is None:
            cam_map = {c: i for i, c in enumerate(sorted({cam for _, _, cam in raw}))}
        pid_map = {pid: i for i, pid in enumerate(sorted({pid for _, pid, _ in raw}))}
        out = []
        for p, pid, cam in raw:
            label = pid_map[pid] if relabel else pid
            out.append((p, label, cam_map.get(cam, len(cam_map)), 0))
        return out, cam_map


_mdl.__factory["persondet"] = PersondetReID

# Warm-start from an existing CLIP-ReID checkpoint. The official trainer never
# calls load_param, so wrap make_model instead: train_clipreid does
# `from model.make_model_clipreid import make_model` at its own import time,
# which happens inside runpy below — so patching the module attribute now is
# picked up. Identity- and camera-sized tensors (classifier, classifier_proj,
# prompt_learner.cls_ctx, cv_embed) cannot transfer to a dataset with a
# different identity/camera count, so they are skipped on shape mismatch and
# stay randomly initialised.
__WARM_START__


sys.argv = ["train_clipreid.py", "--config_file", __CONFIG_FILE__] + __OPTS__
runpy.run_path("train_clipreid.py", run_name="__main__")
'''

_WARM_START_TEMPLATE = """import torch
import model.make_model_clipreid as _mm

_WEIGHTS = __WEIGHTS__
_orig_make_model = _mm.make_model


def _load_transferable(net, path):
    sd = torch.load(path, map_location="cpu", weights_only=False)
    if isinstance(sd, dict) and "state_dict" in sd:
        sd = sd["state_dict"]
    own = net.state_dict()
    loaded, skipped = [], []
    for k, v in sd.items():
        key = k.replace("module.", "")
        if key in own and own[key].shape == v.shape:
            own[key].copy_(v)
            loaded.append(key)
        else:
            skipped.append(key)
    print("[warm-start] loaded {}/{} tensors from {}".format(len(loaded), len(sd), path))
    print("[warm-start] skipped (shape mismatch or absent): {}".format(sorted(skipped)))
    if not loaded:
        raise RuntimeError("warm-start loaded 0 tensors — wrong checkpoint for this architecture?")


def _make_model_warm(cfg, num_class, camera_num, view_num):
    net = _orig_make_model(cfg, num_class=num_class, camera_num=camera_num, view_num=view_num)
    _load_transferable(net, _WEIGHTS)
    return net


_mm.make_model = _make_model_warm
"""


def _require_checkout() -> None:
    """Fail loudly (with the fix) when the official checkout is absent."""
    if not (CLIPREID_DIR / "train_clipreid.py").is_file():
        raise FileNotFoundError(
            f"CLIP-ReID checkout not found at {CLIPREID_DIR}. Clone it with:\n"
            f"  git clone https://github.com/Syliz517/CLIP-ReID.git {CLIPREID_DIR}\n"
            f"(pinned commit {PINNED_COMMIT})"
        )
    head = subprocess.run(
        ["git", "-C", str(CLIPREID_DIR), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    if head and head != PINNED_COMMIT:
        logger.warning("CLIP-ReID checkout at %s, expected %s", head[:12], PINNED_COMMIT[:12])


