"""CLIP-ReID pipeline — orchestrates the official two-stage trainer.

Training is delegated to the official CLIP-ReID codebase (Syliz517/CLIP-ReID,
MIT — expected as a checkout under ``third_party/CLIP-ReID``; see
:data:`CLIPREID_DIR`). Re-implementing its two-stage recipe (stage 1 learns
identity prompts, stage 2 fine-tunes the image encoder with ID + triplet +
image-to-text losses) is not worth the drift risk, so this module instead:

  1. generates a yacs config matching the DEPLOYED encoder architecture
     (ViT-B/16, overlapping patches stride 12, SIE camera embeddings, 256x128 —
     the ``12x12sie`` family consumed by TRACE's ``piaspace_clip_reid``);
  2. generates a small launcher that registers our Market-1501-layout dataset
     in the official ``__factory`` (their ``Market1501`` class hard-asserts
     ``pid <= 1501`` / ``camid <= 6``, so it cannot ingest MTMDC's 16 cameras)
     and then executes their unmodified ``train_clipreid.py`` via ``runpy``;
  3. runs the launcher as a subprocess (their top-level module names —
     ``config``, ``datasets``, ``model`` — are too generic to import in-process
     safely).

The resulting ``ViT-B-16_<epoch>.pth`` is the exact format TRACE consumes
(``piaspace_clip_reid`` strips ``image_encoder.``/keeps ``bottleneck.*``), and
converts to a TRT engine with the existing
``scripts/conversion/convert_clipreid_to_trt.sh person --weights <pth>``.

Evaluation deliberately embeds through the DEPLOYED ``piaspace_clip_reid``
encoder (PyTorch path) rather than the training code — every eval is thereby
also a deployment-contract test.
"""

