def train(config: ClipReIDExperimentConfig) -> Path:
    """Run the official two-stage CLIP-ReID fine-tune on our dataset.

    Args:
        config: The validated experiment configuration.

    Returns:
        Path to the final checkpoint
        (``runs/reid/<name>/<backbone>_<stage2_epochs>.pth``) — directly
        consumable by TRACE's ``piaspace_clip_reid`` and the TRT converter.

    Raises:
        FileNotFoundError: If the third_party checkout, dataset, or
            ``train.pretrain_weights`` checkpoint is missing.
        RuntimeError: If the subprocess exits non-zero.
    """
    _require_checkout()
    warm = config.train.pretrain_weights
    if warm is not None and not Path(warm).is_file():
        raise FileNotFoundError(f"pretrain_weights checkpoint not found: {warm}")
    load_market_dataset(config.data.dataset_dir)  # fail fast on layout problems

    out_dir = (RUNS_DIR / config.train.name).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg_path = out_dir / "official_config.yml"
    cfg_path.write_text(yaml.safe_dump(_official_config(config, out_dir), sort_keys=False))

    opts = [str(x) for kv in config.train.extra.items() for x in kv]
    launcher = out_dir / "launcher.py"
    warm_block = (
        _WARM_START_TEMPLATE.replace("__WEIGHTS__", repr(str(Path(warm).resolve())))
        if warm is not None
        else ""
    )
    launcher_code = (
        _LAUNCHER_TEMPLATE.replace("__CONFIG_FILE__", repr(str(cfg_path)))
        .replace("__OPTS__", repr(opts))
        .replace("__WARM_START__", warm_block)
    )
    launcher.write_text(launcher_code)
    if warm is not None:
        logger.info("warm-starting from %s (identity/camera tensors will be skipped)", warm)

    env = dict(os.environ)
    # The launcher runs by absolute path, so cwd is not on sys.path — the
    # official repo's top-level modules (datasets/, model/, ...) need this.
    env["PYTHONPATH"] = str(CLIPREID_DIR) + os.pathsep + env.get("PYTHONPATH", "")
    if config.train.device not in ("auto", "cpu"):
        env["CUDA_VISIBLE_DEVICES"] = config.train.device.removeprefix("cuda:")
    log_path = out_dir / "train.log"
    logger.info("CLIP-ReID two-stage train -> %s (log: %s)", out_dir, log_path)
    with open(log_path, "w", encoding="utf-8") as log_fh:
        result = subprocess.run(
            [sys.executable, str(launcher)],
            cwd=CLIPREID_DIR,
            env=env,
            stdout=log_fh,
            stderr=subprocess.STDOUT,
            check=False,
        )
    if result.returncode != 0:
        raise RuntimeError(f"CLIP-ReID training failed (exit {result.returncode}) — see {log_path}")
    ckpt = out_dir / f"{config.model.backbone}_{config.train.stage2_epochs}.pth"
    logger.info(
        "CLIP-ReID checkpoint: %s (TRACE-ready; convert via "
        "convert_clipreid_to_trt.sh person --weights <path>)",
        ckpt,
    )
    return ckpt


def _deployed_embedder(config: ClipReIDExperimentConfig, weights: str) -> Any:
    """Instantiate TRACE's ``piaspace_clip_reid`` embedder (PyTorch path)."""
    pkg = Path(config.train.piaspace_pkg)
    if not (pkg / "piaspace_clip_reid").is_dir():
        raise FileNotFoundError(
            f"piaspace_clip_reid not found under {pkg} — set train.piaspace_pkg to "
            "<TRACE repo>/packages/piaspace-clip-reid/src"
        )
    if str(pkg) not in sys.path:
        sys.path.insert(0, str(pkg))
    from piaspace_clip_reid import CLIPReIDEmbedder

    return CLIPReIDEmbedder(
        {
            "device": resolve_torch_device(config.train.device),
            "input_size": list(config.model.input_size),
            "stride": config.model.stride,
            "weights_path": weights,
        }
    )


def _embed_split(embedder: Any, split: ReIDSplit, batch: int = 64) -> np.ndarray:
    import cv2

    feats: list[np.ndarray] = []
    for i in range(0, len(split.paths), batch):
        crops = [cv2.imread(str(p)) for p in split.paths[i : i + batch]]
        feats.append(embedder.embed(crops))
    return np.concatenate(feats, axis=0)


def evaluate(
    config: ClipReIDExperimentConfig,
    weights: str,
    split: str = "test",
    conf: float | None = None,
) -> dict[str, float]:
    """mAP / CMC on query-gallery, embedded through the DEPLOYED encoder.

    Using ``piaspace_clip_reid`` (not the training code) makes every eval a
    deployment-contract test: if the checkpoint fails to load or embeds
    garbage here, it would do the same inside TRACE.

    Args:
        config: The experiment configuration.
        weights: Path to a CLIP-ReID ``.pth`` checkpoint.
        split: Accepted for registry-signature compatibility (unused).
        conf: Unused for ReID (registry-signature compatibility).

    Returns:
        ``{"mAP": ..., "rank1": ..., ...}``.
    """
    del split, conf
    # Evaluation-only sets (e.g. pia_aihub4_v1) ship an empty train split by
    # design; only query/gallery are read below.
    data = load_market_dataset(config.data.dataset_dir, require_train=False)
    embedder = _deployed_embedder(config, weights)
    q = _embed_split(embedder, data.query)
    g = _embed_split(embedder, data.gallery)
    return evaluate_retrieval(
        q, data.query.pids, data.query.camids, g, data.gallery.pids, data.gallery.camids
    )


def predict(
    config: ClipReIDExperimentConfig,
    weights: str,
    source: Path,
    output: Path,
    conf: float = 0.25,
) -> Any:
    """Embed every crop under ``source`` with the deployed encoder.

    Args:
        config: The experiment configuration.
        weights: Path to a CLIP-ReID ``.pth`` checkpoint.
        source: Directory of person crops.
        output: Output directory for ``features.npy`` + ``index.csv``.
        conf: Unused for ReID (registry-signature compatibility).

    Returns:
        The ``[N, dim]`` feature matrix.
    """
    del conf
    paths = sorted(Path(source).glob("*.jpg")) + sorted(Path(source).glob("*.png"))
    split = ReIDSplit(paths, np.zeros(len(paths), np.int64), np.zeros(len(paths), np.int64))
    embedder = _deployed_embedder(config, weights)
    feats = _embed_split(embedder, split)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    np.save(output / "features.npy", feats)
    (output / "index.csv").write_text("\n".join(str(p) for p in paths) + "\n")
    logger.info("embedded %d crops -> %s", len(paths), output)
    return feats
